/*
# Yenza core database — 8 MVP tables

Creates the foundational schema for the Yenza platform: worker and employer
profiles, a services catalogue, worker-service links, jobs, job applications,
job files, worker credentials, and reviews.

## 1. New Tables

### profiles
One row per account (worker or employer). Replaces the separate worker/employer
profile mock objects.
- id (uuid PK, references auth.users)
- first_name, surname, display_name
- phone, email, preferred_language, bio, profile_photo
- role: 'worker' | 'employer'
- account_type: for employers ('Household', 'Landlord', 'Small business', 'Organisation')
- primary_location (text)
- service_areas (jsonb array of area names)
- availability (jsonb — days of week + current status)
- worker_status: 'available' | 'busy' | 'unavailable' (for workers)
- identity_verified (boolean)
- is_available (boolean, convenience flag)
- experience_level (text, for workers)
- experience_detail (text, for workers)
- qualifications_summary (jsonb — identity/qualification/registration checks)
- created_at, updated_at

### services
Master catalogue of services.
- id (uuid PK)
- name (unique)
- category: 'General Work' | 'Skilled Services'
- slug (unique)
- active (boolean)

### worker_services
Links workers to services they offer.
- id (uuid PK)
- worker_id (uuid FK → profiles.id)
- service_id (uuid FK → services.id)
- experience_level, years_experience, description, starting_price, pricing_type
- active (boolean)
- unique (worker_id, service_id)

### jobs
Central job record from posting to completion.
- id (uuid PK)
- employer_id (uuid FK → profiles.id)
- assigned_worker_id (uuid FK → profiles.id, nullable)
- service_id (uuid FK → services.id, nullable)
- title, description, job_location, private_address
- budget, agreed_price, pricing_type
- requested_date, requested_time, confirmed_date, confirmed_time
- estimated_duration, materials_required
- latitude, longitude (double precision)
- status: 'Available' | 'Accepted' | 'Completed' | 'Cancelled' | 'Declined'
- completion_details (jsonb)
- created_at, updated_at

### job_applications
Workers applying for posted jobs.
- id (uuid PK)
- job_id (uuid FK → jobs.id)
- worker_id (uuid FK → profiles.id)
- message, proposed_price, estimated_duration
- status: 'pending' | 'accepted' | 'declined'
- unique (job_id, worker_id)
- created_at

### job_files
References to photos/videos/documents stored in Supabase Storage.
- id (uuid PK)
- job_id (uuid FK → jobs.id)
- uploader_id (uuid FK → profiles.id, nullable)
- file_path, file_type, purpose, caption
- created_at

### worker_credentials
Qualifications, certificates and their verification.
- id (uuid PK)
- worker_id (uuid FK → profiles.id)
- credential_name, institution, type, field_of_study
- issue_date, expiry_date
- document_path
- verification_status: 'not_verified' | 'verified' | 'rejected'
- reviewer_id (uuid nullable), review_date, notes
- created_at, updated_at

### reviews
Trust and reputation after job completion.
- id (uuid PK)
- job_id (uuid FK → jobs.id)
- reviewer_id (uuid FK → profiles.id)
- reviewed_id (uuid FK → profiles.id)
- rating (1–5), written_review
- is_visible (boolean)
- unique (job_id, reviewer_id)
- created_at

## 2. Security (RLS)
- All tables have RLS enabled.
- Profiles: owner can read/update own row; authenticated users can read all
  profiles (needed for marketplace browsing).
- Services: public read (catalogue).
- Worker_services: public read; owner can CRUD own entries.
- Jobs: authenticated can read all jobs (marketplace); employer owner can
  insert/update/delete own jobs; assigned worker can update job status.
- Job_applications: job owner and applicant can read; worker can insert own;
  applicant can update/delete own; job owner can update status.
- Job_files: job participants can read; uploader can insert/delete own.
- Worker_credentials: owner can CRUD; public can read verification status only.
- Reviews: public read visible reviews; reviewer can insert/update/delete own.

## 3. Indexes
- profiles: role, phone (unique)
- services: category, slug
- worker_services: worker_id, service_id
- jobs: employer_id, assigned_worker_id, service_id, status, job_location
- job_applications: job_id, worker_id, status
- job_files: job_id
- worker_credentials: worker_id, verification_status
- reviews: reviewed_id, job_id

## Important Notes
1. UUIDs generated by gen_random_uuid().
2. updated_at auto-updated via trigger on profiles, jobs, worker_credentials.
3. All FK references use ON DELETE CASCADE for child tables.
4. Demo auth users are created in the seeding migration (next step).
*/

-- Extensions
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ============================================================
-- PROFILES
-- ============================================================
CREATE TABLE IF NOT EXISTS profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  first_name text NOT NULL DEFAULT '',
  surname text NOT NULL DEFAULT '',
  display_name text NOT NULL DEFAULT '',
  phone text UNIQUE,
  email text,
  preferred_language text DEFAULT 'English',
  bio text DEFAULT '',
  profile_photo text DEFAULT '',
  role text NOT NULL DEFAULT 'worker' CHECK (role IN ('worker', 'employer')),
  account_type text CHECK (account_type IN ('Household', 'Landlord', 'Small business', 'Organisation')),
  primary_location text DEFAULT '',
  service_areas jsonb DEFAULT '[]'::jsonb,
  availability jsonb DEFAULT '{}'::jsonb,
  worker_status text DEFAULT 'available' CHECK (worker_status IN ('available', 'busy', 'unavailable')),
  identity_verified boolean DEFAULT false,
  is_available boolean DEFAULT true,
  experience_level text DEFAULT '',
  experience_detail text DEFAULT '',
  qualifications_summary jsonb DEFAULT '[]'::jsonb,
  profile_photo_set boolean DEFAULT false,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

ALTER TABLE profiles ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "select_profiles" ON profiles;
CREATE POLICY "select_profiles" ON profiles FOR SELECT
  TO authenticated USING (true);

DROP POLICY IF EXISTS "insert_own_profile" ON profiles;
CREATE POLICY "insert_own_profile" ON profiles FOR INSERT
  TO authenticated WITH CHECK (auth.uid() = id);

DROP POLICY IF EXISTS "update_own_profile" ON profiles;
CREATE POLICY "update_own_profile" ON profiles FOR UPDATE
  TO authenticated USING (auth.uid() = id) WITH CHECK (auth.uid() = id);

CREATE INDEX IF NOT EXISTS idx_profiles_role ON profiles(role);
CREATE INDEX IF NOT EXISTS idx_profiles_phone ON profiles(phone);

-- ============================================================
-- SERVICES
-- ============================================================
CREATE TABLE IF NOT EXISTS services (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text UNIQUE NOT NULL,
  category text NOT NULL CHECK (category IN ('General Work', 'Skilled Services')),
