-- ============================================================
-- JOBS
-- ============================================================
CREATE TABLE IF NOT EXISTS jobs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  employer_id uuid NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  assigned_worker_id uuid REFERENCES profiles(id) ON DELETE SET NULL,
  service_id uuid REFERENCES services(id) ON DELETE SET NULL,
  title text NOT NULL,
  description text DEFAULT '',
  job_location text NOT NULL DEFAULT '',
  private_address text DEFAULT '',
  budget numeric NOT NULL DEFAULT 0,
  agreed_price numeric,
  pricing_type text DEFAULT 'fixed',
  requested_date text,
  requested_time text,
  confirmed_date text,
  confirmed_time text,
  estimated_duration text DEFAULT '',
  materials_required text DEFAULT '',
  latitude double precision DEFAULT 0,
  longitude double precision DEFAULT 0,
  status text NOT NULL DEFAULT 'Available' CHECK (status IN ('Available', 'Accepted', 'Completed', 'Cancelled', 'Declined')),
  completion_details jsonb DEFAULT '{}'::jsonb,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

ALTER TABLE jobs ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "select_jobs" ON jobs;
CREATE POLICY "select_jobs" ON jobs FOR SELECT
  TO authenticated USING (true);

DROP POLICY IF EXISTS "insert_own_jobs" ON jobs;
CREATE POLICY "insert_own_jobs" ON jobs FOR INSERT
  TO authenticated WITH CHECK (auth.uid() = employer_id);

DROP POLICY IF EXISTS "update_own_jobs" ON jobs;
CREATE POLICY "update_own_jobs" ON jobs FOR UPDATE
  TO authenticated USING (auth.uid() = employer_id OR auth.uid() = assigned_worker_id)
  WITH CHECK (auth.uid() = employer_id OR auth.uid() = assigned_worker_id);

DROP POLICY IF EXISTS "delete_own_jobs" ON jobs;
CREATE POLICY "delete_own_jobs" ON jobs FOR DELETE
  TO authenticated USING (auth.uid() = employer_id);

CREATE INDEX IF NOT EXISTS idx_jobs_employer ON jobs(employer_id);
CREATE INDEX IF NOT EXISTS idx_jobs_worker ON jobs(assigned_worker_id);
CREATE INDEX IF NOT EXISTS idx_jobs_service ON jobs(service_id);
CREATE INDEX IF NOT EXISTS idx_jobs_status ON jobs(status);
CREATE INDEX IF NOT EXISTS idx_jobs_location ON jobs(job_location);

-- ============================================================
-- JOB_APPLICATIONS
-- ============================================================
CREATE TABLE IF NOT EXISTS job_applications (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  job_id uuid NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
  worker_id uuid NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  message text DEFAULT '',
  proposed_price numeric,
  estimated_duration text DEFAULT '',
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'accepted', 'declined')),
  created_at timestamptz DEFAULT now(),
  UNIQUE (job_id, worker_id)
);

ALTER TABLE job_applications ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "select_job_applications" ON job_applications;
CREATE POLICY "select_job_applications" ON job_applications FOR SELECT
  TO authenticated USING (
    auth.uid() = worker_id
    OR EXISTS (SELECT 1 FROM jobs WHERE jobs.id = job_applications.job_id AND jobs.employer_id = auth.uid())
  );

DROP POLICY IF EXISTS "insert_own_job_applications" ON job_applications;
CREATE POLICY "insert_own_job_applications" ON job_applications FOR INSERT
  TO authenticated WITH CHECK (auth.uid() = worker_id);

DROP POLICY IF EXISTS "update_own_job_applications" ON job_applications;
CREATE POLICY "update_own_job_applications" ON job_applications FOR UPDATE
  TO authenticated USING (
    auth.uid() = worker_id
    OR EXISTS (SELECT 1 FROM jobs WHERE jobs.id = job_applications.job_id AND jobs.employer_id = auth.uid())
  )
  WITH CHECK (
    auth.uid() = worker_id
    OR EXISTS (SELECT 1 FROM jobs WHERE jobs.id = job_applications.job_id AND jobs.employer_id = auth.uid())
  );

DROP POLICY IF EXISTS "delete_own_job_applications" ON job_applications;
CREATE POLICY "delete_own_job_applications" ON job_applications FOR DELETE
  TO authenticated USING (auth.uid() = worker_id);

CREATE INDEX IF NOT EXISTS idx_job_applications_job ON job_applications(job_id);
CREATE INDEX IF NOT EXISTS idx_job_applications_worker ON job_applications(worker_id);
CREATE INDEX IF NOT EXISTS idx_job_applications_status ON job_applications(status);

